//! Process-level tests of the startup schema check (fix-stale-settings-schema): the real `annota`
//! binary against schema directories built in a temp dir, with a clean environment so neither the
//! session's `XDG_DATA_DIRS` nor a display is used.
//!
//! The binary loads its gresource from the configured `PKGDATADIR` after the check. Where that
//! file is not installed (CI), a run that gets past the check ends with "annota: cannot load".
//! There, "Matching schema starts normally" and "Version and help without a schema" prove only
//! that the check was passed and no schema message was printed; that the app then really starts,
//! prints its version and its usage is proven by the live rows in the change's
//! `manual-checks.md`. Where the gresource is installed, these tests prove the exit codes too.
//!
//! `report_is_german_under_language_de` needs a working `bwrap` (unprivileged user namespaces)
//! and an `en_US` or `de_DE` locale. Without them it prints "skipped" and passes, so on such a
//! runner it proves nothing; the change's `manual-checks.md` row for "Report in the user's
//! language" holds the real-binary evidence.

use std::path::{Path, PathBuf};
use std::process::{Command, Output};

#[allow(dead_code)]
mod config {
    // The binary's LOCALEDIR, generated by Meson like the binary's own copy.
    include!(concat!(env!("CARGO_MANIFEST_DIR"), "/src/config.rs"));
}

const SCHEMA_FILE: &str = "io.github.trosinde.Annota.gschema.xml";

const STALE: &str = r#"<?xml version="1.0" encoding="UTF-8"?>
<schemalist gettext-domain="annota">
  <schema id="io.github.trosinde.Annota" path="/io/github/trosinde/Annota/">
    <key name="save-folder" type="s"><default>''</default></key>
    <key name="shortcut-region" type="s"><default>'Print'</default></key>
  </schema>
</schemalist>
"#;

struct Tmp(PathBuf);

impl Tmp {
    fn new(name: &str) -> Self {
        let dir = std::env::temp_dir().join(format!(
            "annota-schema-process-{name}-{}",
            std::process::id()
        ));
        let _ = std::fs::remove_dir_all(&dir);
        std::fs::create_dir_all(&dir).unwrap();
        Self(dir)
    }

    /// `<tmp>/<name>` as an XDG data dir whose `glib-2.0/schemas` holds `xml`, compiled.
    fn data_dir(&self, name: &str, xml: Option<&str>) -> PathBuf {
        let root = self.0.join(name);
        let schemas = root.join("glib-2.0").join("schemas");
        std::fs::create_dir_all(&schemas).unwrap();
        if let Some(xml) = xml {
            std::fs::write(schemas.join(SCHEMA_FILE), xml).unwrap();
            let status = Command::new("glib-compile-schemas")
                .arg(&schemas)
                .status()
                .unwrap();
            assert!(status.success());
        }
        root
    }
}

impl Drop for Tmp {
    fn drop(&mut self) {
        let _ = std::fs::remove_dir_all(&self.0);
    }
}

fn shipped() -> String {
    std::fs::read_to_string(
        Path::new(env!("CARGO_MANIFEST_DIR"))
            .join("data")
            .join(SCHEMA_FILE),
    )
    .unwrap()
}

fn run(tmp: &Tmp, data_dirs: &[&Path], args: &[&str]) -> (Output, String) {
    let joined = data_dirs
        .iter()
        .map(|dir| dir.display().to_string())
        .collect::<Vec<_>>()
        .join(":");
    let output = Command::new(env!("CARGO_BIN_EXE_annota"))
        .args(args)
        .env_clear()
        .env("PATH", std::env::var_os("PATH").unwrap_or_default())
        .env("HOME", &tmp.0)
        .env("XDG_DATA_HOME", tmp.0.join("user-data"))
        .env("XDG_CONFIG_HOME", tmp.0.join("config"))
        .env("XDG_DATA_DIRS", joined)
        .env("GSETTINGS_BACKEND", "memory")
        .env("LANG", "C")
        .output()
        .unwrap();
    let stderr = String::from_utf8_lossy(&output.stderr).into_owned();
    (output, stderr)
}

fn assert_no_glib_abort(output: &Output, stderr: &str) {
    assert!(!stderr.contains("GLib-GIO-ERROR"), "{stderr}");
    assert!(
        output.status.code().is_some(),
        "killed by a signal: {stderr}"
    );
}

/// The process got past the schema check: no schema report, and it either did its job or stopped
/// at the gresource load that follows the check.
fn assert_past_the_check(output: &Output, stderr: &str, expected_code: i32) {
    assert_no_glib_abort(output, stderr);
    assert!(!stderr.contains("settings schema"), "{stderr}");
    let resources_missing = stderr.contains("annota: cannot load");
    assert!(
        output.status.code() == Some(expected_code)
            || (resources_missing && output.status.code() == Some(1)),
        "{:?}: {stderr}",
        output.status
    );
}

// spec: app-shell / Settings schema check at startup / Stale schema shadows the installed one
#[test]
fn stale_schema_ends_the_process_with_status_1() {
    let tmp = Tmp::new("stale");
    let stale = tmp.data_dir("usr-local-share", Some(STALE));
    let installed = tmp.data_dir("usr-share", Some(&shipped()));
    let (output, stderr) = run(&tmp, &[&stale, &installed], &[]);
    assert_no_glib_abort(&output, &stderr);
    assert_eq!(output.status.code(), Some(1), "{stderr}");
    assert!(stderr.contains("missing keys: "), "{stderr}");
    assert!(stderr.contains("shortcut-record"), "{stderr}");
    let in_use = format!(
        "{} (in use,",
        stale.join("glib-2.0/schemas/gschemas.compiled").display()
    );
    let shadowed = format!(
        "{} (shadowed, complete)",
        installed
            .join("glib-2.0/schemas/gschemas.compiled")
            .display()
    );
    let in_use_at = stderr.find(&in_use).expect(&stderr);
    let shadowed_at = stderr.find(&shadowed).expect(&stderr);
    assert!(in_use_at < shadowed_at);
    assert!(stderr.lines().all(|line| line.starts_with("annota: ")));
}

// spec: app-shell / Settings schema check at startup / Schema not installed
#[test]
fn missing_schema_ends_the_process_with_status_1() {
    let tmp = Tmp::new("missing");
    let empty = tmp.data_dir("empty", None);
    let (output, stderr) = run(&tmp, &[&empty], &[]);
    assert_no_glib_abort(&output, &stderr);
    assert_eq!(output.status.code(), Some(1), "{stderr}");
    assert!(
        stderr.contains("the settings schema io.github.trosinde.Annota is not installed."),
        "{stderr}"
    );
    assert!(stderr.contains("reinstall Annota"), "{stderr}");
}

// spec: app-shell / Settings schema check at startup / Matching schema starts normally
#[test]
fn matching_schema_gets_past_the_check() {
    let tmp = Tmp::new("matching");
    let installed = tmp.data_dir("usr-share", Some(&shipped()));
    // An invalid mode ends the process right after option parsing, before any window.
    let (output, stderr) = run(&tmp, &[&installed], &["--capture", "banana"]);
    assert_past_the_check(&output, &stderr, 2);
    if output.status.code() == Some(2) {
        assert!(stderr.contains("Valid modes"), "{stderr}");
    }
}

// spec: app-shell / Settings schema check at startup / Version and help without a schema
#[test]
fn version_and_help_need_no_schema() {
    let tmp = Tmp::new("version");
    let empty = tmp.data_dir("empty", None);
    let (output, stderr) = run(&tmp, &[&empty], &["--version"]);
    assert_past_the_check(&output, &stderr, 0);
    if output.status.code() == Some(0) {
        assert!(String::from_utf8_lossy(&output.stdout).starts_with("annota "));
    }
    let (output, stderr) = run(&tmp, &[&empty], &["--help"]);
    assert_past_the_check(&output, &stderr, 0);
}

/// A locale other than C/POSIX: under C (and C.UTF-8) gettext ignores `LANGUAGE`.
fn non_c_locale() -> Option<&'static str> {
    let output = Command::new("locale").arg("-a").output().ok()?;
    let installed = String::from_utf8_lossy(&output.stdout).to_lowercase();
    [("en_US.UTF-8", "en_us.utf8"), ("de_DE.UTF-8", "de_de.utf8")]
        .into_iter()
        .find(|(_, listed)| installed.lines().any(|line| line == *listed))
        .map(|(name, _)| name)
}

// spec: app-shell / Settings schema check at startup / Report in the user's language
#[test]
fn report_is_german_under_language_de() {
    // The real binary reads translations from its compiled-in LOCALEDIR; bwrap overlays a
    // freshly compiled de/annota.mo there in a private mount namespace, without root.
    let locale_dir = Path::new(config::LOCALEDIR);
    let bwrap_works = Command::new("bwrap")
        .args(["--dev-bind", "/", "/", "true"])
        .status()
        .is_ok_and(|status| status.success());
    let Some(locale) = non_c_locale() else {
        eprintln!("skipped: no en_US.UTF-8 or de_DE.UTF-8 locale installed");
        return;
    };
    if !bwrap_works || !locale_dir.is_dir() {
        eprintln!(
            "skipped: bwrap unusable or {} missing",
            locale_dir.display()
        );
        return;
    }
    let tmp = Tmp::new("german");
    let messages = tmp.0.join("locale").join("de").join("LC_MESSAGES");
    std::fs::create_dir_all(&messages).unwrap();
    let po = Path::new(env!("CARGO_MANIFEST_DIR")).join("po/de.po");
    assert!(Command::new("msgfmt")
        .arg("-o")
        .arg(messages.join("annota.mo"))
        .arg(po)
        .status()
        .unwrap()
        .success());
    let empty = tmp.data_dir("empty", None);

    let run_in = |language: &str| {
        let output = Command::new("bwrap")
            .args(["--dev-bind", "/", "/", "--tmpfs"])
            .arg(locale_dir)
            .arg("--ro-bind")
            .arg(tmp.0.join("locale").join("de"))
            .arg(locale_dir.join("de"))
            .arg(env!("CARGO_BIN_EXE_annota"))
            .env_clear()
            .env("PATH", std::env::var_os("PATH").unwrap_or_default())
            .env("HOME", &tmp.0)
            .env("XDG_DATA_HOME", tmp.0.join("user-data"))
            .env("XDG_DATA_DIRS", &empty)
            .env("LANG", locale)
            .env("LANGUAGE", language)
            .output()
            .unwrap();
        let stderr = String::from_utf8_lossy(&output.stderr).into_owned();
        (output, stderr)
    };

    let (output, stderr) = run_in("de");
    assert_no_glib_abort(&output, &stderr);
    assert_eq!(output.status.code(), Some(1), "{stderr}");
    assert!(
        stderr.contains(
            "annota: Das Einstellungsschema io.github.trosinde.Annota ist nicht installiert."
        ),
        "{stderr}"
    );
    assert!(stderr.contains("Installieren Sie Annota neu."), "{stderr}");
    assert!(stderr.lines().all(|line| line.starts_with("annota: ")));

    // The same binary in English: the German came from the user's language, not the build.
    let (_, stderr) = run_in("en");
    assert!(
        stderr.contains("annota: the settings schema io.github.trosinde.Annota is not installed."),
        "{stderr}"
    );
}
